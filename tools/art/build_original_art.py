def identify_component(name: str):
    for marker, kind, family in COMPONENT_KIND:
        if marker.lower() in name.lower():
            return kind, family
    if "Weapon" in name: return "cannon", "weapon"
    return "support_matrix", "support"


def identify_facility(name: str):
    for marker, kind, family in FACILITY_KIND:
        if marker.lower() in name.lower():
            return kind, family
    return "warehouse", "cargo"


