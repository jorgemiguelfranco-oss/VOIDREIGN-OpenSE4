def records(path: Path) -> list[dict[str, str]]:
    text = path.read_text(encoding="utf-8-sig", errors="replace")
    chunks = re.split(r"(?=^Name\s*: =|^Name\s*:=)", text, flags=re.M)
    result = []
    for chunk in chunks:
        fields = {}
        for line in chunk.splitlines():
            if ":=" in line:
                key, value = line.split(":=", 1)
                fields[key.strip()] = value.strip()
        if fields.get("Name"):
            result.append(fields)
    return result


def stable_seed(value: str) -> int:
    return int.from_bytes(hashlib.sha256(value.encode("utf-8")).digest()[:4], "little")


def scaled_box(box):
    return tuple(int(round(v * SCALE)) for v in box)


def palette_for(family: str, name: str, index: int):
    base = PALETTES.get(family, PALETTES["neutral"])
    # Each record has a controlled, small hue shift while retaining its
    # functional family colour: upgrade art is distinct but recognisable.
    seed = stable_seed(name + str(index))
    shift = ((seed % 13) - 6) * 1.1
    def alter(c):
        return tuple(max(0, min(255, int(v + (shift if i != 2 else -shift * 0.55)))) for i, v in enumerate(c))
    return alter(base[0]), alter(base[1]), alter(base[2])


def make_portrait(name: str, kind: str, family: str, level: int, index: int) -> Image.Image:
    seed = stable_seed(name + "|" + kind + "|" + str(index))
    rng = seed
    a, hi, shadow = palette_for(family, name, index)
    im = Image.new("RGBA", (CANVAS, CANVAS), (2, 6, 17, 255))
    px = im.load()
    # Deep navy vertical gradient with a subtle central energy halo.
    cx, cy = CANVAS * 0.5, CANVAS * 0.48
    for y in range(CANVAS):
        for x in range(CANVAS):
            radial = max(0.0, 1.0 - math.sqrt(((x-cx)/(CANVAS*.83))**2 + ((y-cy)/(CANVAS*.83))**2))
            glow = radial ** 2 * 0.34
            stripe = 0.025 * math.sin(y / 41.0 + (seed % 20))
            px[x, y] = (
                int(4 + (a[0] * .12) * glow + 7 * stripe),
                int(8 + (a[1] * .10) * glow + 12 * stripe),
                int(19 + (a[2] * .09) * glow + 22 * stripe),
                255,
            )
    d = ImageDraw.Draw(im, "RGBA")
    # Fine star points and circuitry lines.
    for n in range(30):
        x = 18 + ((seed >> (n % 24) ^ (n * 7919)) % 348)
        y = 24 + ((seed >> (n % 20) ^ (n * 3571)) % 330)
        r = 2 if n % 6 else 3
        d.ellipse((x-r, y-r, x+r, y+r), fill=(*hi, 100 if n % 3 else 175))
    # Bevelled dark frame and inner luminous edge.
    d.rounded_rectangle((10, 10, 374, 374), radius=36, fill=(7, 16, 31, 245), outline=(115, 155, 189, 230), width=5)
    d.rounded_rectangle((19, 19, 365, 365), radius=29, outline=(*a, 185), width=3)
    d.line((40, 30, 344, 30), fill=(230, 244, 255, 95), width=3)
    d.line((30, 42, 30, 335), fill=(150, 197, 226, 75), width=2)
    d.line((354, 42, 354, 335), fill=(0, 0, 0, 155), width=3)
    # Object halo behind the device.
    d.ellipse((63, 63, 321, 321), fill=(*a, 17), outline=(*hi, 55), width=3)
    d.ellipse((81, 81, 303, 303), outline=(*a, 55), width=2)
    # Small radial marks communicate high-tech precision.
    for n in range(16):
        angle = n * math.pi / 8
        x1 = 192 + math.cos(angle) * 137
        y1 = 192 + math.sin(angle) * 137
        x2 = 192 + math.cos(angle) * (147 if n % 2 == 0 else 142)
        y2 = 192 + math.sin(angle) * (147 if n % 2 == 0 else 142)
        d.line((x1, y1, x2, y2), fill=(*hi, 135), width=3 if n % 2 == 0 else 2)

    # Original hardware silhouette with layered highlights and bevels.
    d = ImageDraw.Draw(im, "RGBA")
    draw_symbol(d, kind, a, hi, shadow, level, seed, is_shadow=False)

    # Unique upgrade mark. It is ornamental, not a text label.
    d.rounded_rectangle((294, 48, 342, 96), radius=12, fill=(5, 17, 32, 235), outline=(*hi, 230), width=3)
    bars = max(1, min(4, level))
    for n in range(4):
        col = hi if n < bars else (50, 68, 87)
        d.rounded_rectangle((302+n*9, 80-(n+1)*7, 308+n*9, 87), radius=2, fill=(*col, 255))
    # Bottom serial light marks tie every portrait into one premium art system.
    for n in range(5):
        col = a if n < ((index - 1) % 5 + 1) else (39, 63, 83)
        d.rounded_rectangle((54+n*19, 334, 67+n*19, 339), radius=2, fill=(*col, 230))
    return im.resize((SIZE, SIZE), Image.Resampling.LANCZOS)


