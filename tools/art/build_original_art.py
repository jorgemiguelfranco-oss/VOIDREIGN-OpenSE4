def update_data_numbers(path: Path, field: str) -> tuple[list[dict], bytes]:
    raw=path.read_bytes()
    newline=b"\r\n" if b"\r\n" in raw else b"\n"
    text=raw.decode("utf-8-sig")
    matches=list(re.finditer(r"(?m)^Name\s*:=\s*(.+)$",text))
    if not matches: return [],raw
    rows=[]
    out=text
    for i in range(len(matches)-1,-1,-1):
        start=matches[i].start()
        end=matches[i+1].start() if i+1<len(matches) else len(text)
        block=text[start:end]
        name=matches[i].group(1).strip()
        number=i+1
        if re.search(r"(?m)^Pic Num\s*:=",block):
            block=re.sub(r"(?m)^(Pic Num\s*:=\s*)\d+\s*$",rf"\g<1>{number}",block,count=1)
        else:
            # Keep record's existing schema; Pic Num is mandatory for these data files.
            raise RuntimeError(f"{path.name}: {name} has no Pic Num field")
        rows.append({"name":name,"pic":number})
        out=out[:start]+block+out[end:]
    encoded=out.encode("utf-8")
    if newline==b"\r\n": encoded=encoded.replace(b"\r\n",b"\n").replace(b"\n",b"\r\n")
    return rows,encoded


